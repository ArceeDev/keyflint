const json = (v) => JSON.stringify(v, null, 2) + "\n";

const gitignore = (lang) =>
  [".env", ".keyflint/", "*.mcpb", lang === "python" ? "__pycache__/\n.venv/\ndist/\n*.egg-info/\n.pytest_cache/" : "node_modules/\ndist/", ""].join("\n");

const envExample = (c) => `# Copy to .env for local runs. Never commit .env.
# The buyer's license (LIC-...). \`keyflint init\` put a local development license in .env.
KEYFLINT_LICENSE=
# Your gateway: needed by metered (paid) tools. Leave empty to use only free tools.
KEYFLINT_URL=${c.gatewayUrl}
# Where buyers top up when they run out of credits.
KEYFLINT_CHECKOUT_URL=${c.checkoutUrl}
`;

function manifest(c) {
  const isPy = c.lang === "python";
  return json({
    $schema: "https://raw.githubusercontent.com/modelcontextprotocol/mcpb/main/schemas/mcpb-manifest-v0.4.schema.json",
    manifest_version: "0.4",
    name: c.name,
    display_name: c.title,
    version: "0.1.0",
    description: c.description,
    author: { name: c.author },
    server: isPy
      ? {
          type: "uv",
          entry_point: `src/${c.module}/server.py`,
          mcp_config: {
            command: "uv",
            args: ["run", "--directory", "${__dirname}", "--no-dev", "--quiet", c.name],
            env: { KEYFLINT_LICENSE: "${user_config.license_key}" },
          },
        }
      : {
          type: "node",
          entry_point: "src/index.js",
          mcp_config: {
            command: "node",
            args: ["${__dirname}/src/index.js"],
            env: { KEYFLINT_LICENSE: "${user_config.license_key}" },
          },
        },
    tools: [
      { name: "hello", description: "Free example tool (license check only)." },
      { name: "word_count", description: "Paid example tool (1 credit per successful call)." },
    ],
    compatibility: {
      platforms: ["darwin", "win32", "linux"],
      runtimes: isPy ? { python: ">=3.10" } : { node: ">=18.4" },
    },
    user_config: {
      license_key: {
        type: "string",
        title: "License key",
        description: "Your license (starts with LIC-).",
        sensitive: true,
        required: true,
      },
    },
  });
}

function serverJson(c) {
  const pkg = c.lang === "python"
    ? { registryType: "pypi", registryBaseUrl: "https://pypi.org", identifier: c.name }
    : { registryType: "npm", registryBaseUrl: "https://registry.npmjs.org", identifier: c.name };
  return json({
    $schema: "https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json",
    name: `io.github.${c.githubUser}/${c.name}`,
    title: c.title,
    description: c.description.slice(0, 100),
    version: "0.1.0",
    packages: [
      {
        ...pkg,
        version: "0.1.0",
        transport: { type: "stdio" },
        environmentVariables: [
          { name: "KEYFLINT_LICENSE", description: "Your license key (LIC-...).", isRequired: true, isSecret: true, format: "string" },
        ],
      },
    ],
  });
}

