function readme(c) {
  const isPy = c.lang === "python";
  const run = isPy ? "uv run --env-file .env " + c.name : "npm start";
  const local = isPy
    ? { command: "uvx", args: [c.name], env: { KEYFLINT_LICENSE: "LIC-..." } }
    : { command: "npx", args: ["-y", c.name], env: { KEYFLINT_LICENSE: "LIC-..." } };
  return `# ${c.title}

${c.description}

Built with [KeyFlint](https://keyflint.dev): buyers get a license key (verified offline with Ed25519)
and prepaid credits. Paid tools debit credits on your gateway and refund them automatically when they
fail.

## Run it locally

\`\`\`bash
${isPy ? "uv sync\nuv run pytest -q" : "npm install\nnpm test"}
${run}
\`\`\`

\`keyflint init\` created a **development issuer** (\`.keyflint/dev-issuer.pem\`, git-ignored) and a
development license in \`.env\`, so the free tool \`hello\` works right away. Paid tools need a gateway
(\`KEYFLINT_URL\`).

## Connect it to an AI client

Client config (Claude Desktop, Cursor, Windsurf and most others use this shape):

\`\`\`json
${JSON.stringify({ mcpServers: { [c.name]: local } }, null, 2)}
\`\`\`

Claude Code: \`claude mcp add ${c.name} -e KEYFLINT_LICENSE=LIC-... -- ${local.command} ${local.args.join(" ")}\`

Once your server is published, \`npx keyflint links\` prints one-click install links and README badges
for Cursor, VS Code, LM Studio, Goose and more.

## Go live

1. **Gateway.** Run your own (\`docker run ghcr.io/arceedev/keyflint\`, see the
   [KeyFlint README](https://github.com/ArceeDev/keyflint#quickstart)) and connect Stripe.
2. **Trust your gateway, not the dev key.** Put its key ring in \`${isPy ? `src/${c.module}/licensing.py` : "src/licensing.js"}\`
   (\`PUBLIC_KEYS\`), and set \`GATEWAY_URL\` and \`CHECKOUT_URL\`.
3. **Publish.** ${isPy ? "`uv build && uv publish` (PyPI)" : "`npm publish`"}, then the MCP Registry with \`server.json\`
   (\`mcp-publisher publish\`) and a Claude Desktop bundle with \`npx @anthropic-ai/mcpb pack\`.
`;
}

/** Map of relative path -> file content for the chosen language. */
export function projectFiles(c) {
  const common = {
    ".gitignore": gitignore(c.lang),
    ".env.example": envExample(c),
    "README.md": readme(c),
    "manifest.json": manifest(c),
    "server.json": serverJson(c),
  };
  if (c.lang === "python") {
    return {
      ...common,
      "pyproject.toml": pyproject(c),
      [`src/${c.module}/__init__.py`]: `"""${c.title}."""\n\n__version__ = "0.1.0"\n`,
      [`src/${c.module}/__main__.py`]: `from .server import main\n\nmain()\n`,
      [`src/${c.module}/licensing.py`]: pyLicensing(c),
      [`src/${c.module}/logic.py`]: pyLogic(c),
      [`src/${c.module}/server.py`]: pyServer(c),
      "tests/test_server.py": pyTest(c),
    };
  }
  return {
    ...common,
    "package.json": packageJson(c),
    "src/licensing.js": nodeLicensing(c),
    "src/logic.js": nodeLogic(c),
    "src/server.js": nodeServer(c),
    "src/index.js": nodeIndex(c),
    "test/logic.test.js": nodeTest(c),
  };
}
