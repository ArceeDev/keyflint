const nodeServer = (c) => `// ${c.title}: an MCP server that sells its tools with KeyFlint.
// Free tools check the license offline (Ed25519). Paid tools also debit credits on your gateway
// and refund them automatically when the tool fails, so buyers never pay for an error.
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { createKeyFlint } from "keyflint-verify/mcp";
import { z } from "zod";
import { CHECKOUT_URL, GATEWAY_URL, PUBLIC_KEYS } from "./licensing.js";
import { countWords } from "./logic.js";

export const kf = createKeyFlint({
  publicKeys: PUBLIC_KEYS,
  gatewayUrl: process.env.KEYFLINT_URL || GATEWAY_URL || undefined,
  checkoutUrl: process.env.KEYFLINT_CHECKOUT_URL || CHECKOUT_URL || undefined,
});

const text = (value) => ({ content: [{ type: "text", text: typeof value === "string" ? value : JSON.stringify(value) }] });

export const hello = kf.requireLicense(async ({ name }) => text(\`Hello, \${name}!\`));
export const wordCount = kf.metered(1, async ({ text: input }) => text(countWords(input)));

export function createServer() {
  const server = new McpServer({ name: ${JSON.stringify(c.name)}, version: "0.1.0" });
  server.registerTool("hello", { description: "Free for any valid license: greets the user.", inputSchema: { name: z.string() } }, hello);
  server.registerTool(
    "word_count",
    { description: "Paid: counts words and characters (1 credit, refunded if it fails).", inputSchema: { text: z.string() } },
    wordCount,
  );
  return server;
}
`;

const nodeIndex = () => `#!/usr/bin/env node
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { createServer } from "./server.js";

await createServer().connect(new StdioServerTransport());
`;

