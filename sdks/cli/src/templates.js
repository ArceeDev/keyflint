const pyServer = (c) => `"""${c.title}: an MCP server that sells its tools with KeyFlint.

Free tools check the license offline (Ed25519, under 1 ms). Paid tools also debit credits on your
gateway and refund them automatically when the tool fails, so buyers never pay for an error.
"""

from __future__ import annotations

import os

from keyflint_verify.mcp import KeyFlint
from mcp.server.mcpserver import MCPServer

from . import licensing
from .logic import count_words

mcp = MCPServer(${JSON.stringify(c.title)})
kf = KeyFlint(
    public_keys=licensing.PUBLIC_KEYS,
    gateway_url=os.environ.get("KEYFLINT_URL") or licensing.GATEWAY_URL,
    checkout_url=os.environ.get("KEYFLINT_CHECKOUT_URL") or licensing.CHECKOUT_URL,
)


@mcp.tool()
@kf.require_license
def hello(name: str) -> str:
    """Free for any valid license: greets the user."""
    return f"Hello, {name}!"


@mcp.tool()
@kf.metered(credits=1)
def word_count(text: str) -> dict:
    """Paid: counts words and characters (1 credit, refunded if it fails)."""
    return count_words(text)


def main() -> None:
    mcp.run()


if __name__ == "__main__":
    main()
`;

const pyLogic = () => `"""Business logic, kept apart from licensing so it is trivial to test."""

from __future__ import annotations


def count_words(text: str) -> dict:
    return {"words": len(text.split()), "characters": len(text)}
`;

const pyTest = (c) => `"""Runs without network: the development license in .env is checked offline."""

from __future__ import annotations

import os
import pathlib

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]


def _dev_license() -> str:
    env = ROOT / ".env"
    for line in env.read_text(encoding="utf-8").splitlines() if env.exists() else []:
        if line.startswith("KEYFLINT_LICENSE="):
            return line.split("=", 1)[1].strip()
    return ""


def test_logic():
    from ${c.module}.logic import count_words

    assert count_words("one two  three") == {"words": 3, "characters": 14}


def test_free_tool_with_dev_license(monkeypatch):
    lic = _dev_license()
    if not lic:
        pytest.skip("no development license in .env (run: npx keyflint dev-license)")
    from ${c.module} import server

    monkeypatch.setattr(server.kf, "license_key", lic)
    assert server.hello("Ada") == "Hello, Ada!"


def test_free_tool_rejects_missing_license(monkeypatch):
    from keyflint_verify.mcp import LicenseError

    from ${c.module} import server

    monkeypatch.setattr(server.kf, "license_key", "")
    monkeypatch.setattr(server.kf, "_cached", None)
    with pytest.raises(LicenseError):
        server.hello("Ada")
`;

